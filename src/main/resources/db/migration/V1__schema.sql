-- Catalog, promotion and stock rows remember the transaction that last changed them (change_txid). A pull
-- returns rows changed by transactions at or after the client's cursor, and the next cursor is the xmin of the
-- reader's snapshot, so a transaction still in flight during one pull is picked up by the next. Rows can be sent
-- twice; that is harmless because products are replaced whole and stock counters merge by per-node maximum.

create table store (
    code        text primary key check (code ~ '^[A-Z0-9]{2,4}$'),
    name        text not null,
    state_code  char(2) not null,
    gstin       text not null,
    created_at  timestamptz not null default now()
);

create table staff (
    subject     text primary key,
    store_code  text not null references store,
    role        text not null check (role in ('MANAGER', 'CASHIER')),
    name        text not null
);

-- epoch goes up when a terminal is re-enrolled or reset; op-log sequence numbers start again at 1 per epoch.
create table terminal (
    id            uuid primary key,
    store_code    text not null references store,
    number        int not null check (number between 1 and 99),
    subject       text not null unique,
    epoch         int not null,
    last_seq      bigint not null default 0,
    last_push_at  timestamptz,
    enrolled_at   timestamptz not null,
    unique (store_code, number)
);

create table supplier (
    id              uuid primary key,
    name            text not null,
    lead_time_days  int not null check (lead_time_days > 0)
);

create table product (
    sku              text primary key,
    barcode          text not null unique,
    name             text not null,
    hsn              text not null,
    tax_rate         numeric(5, 2) not null check (tax_rate >= 0),
    price            numeric(12, 2) not null check (price > 0),
    cost             numeric(12, 2),
    supplier_id      uuid references supplier,
    low_stock_level  int not null default 5,
    active           boolean not null default true,
    change_txid      xid8 not null default pg_current_xact_id()
);

create table promotion (
    id          uuid primary key,
    code        text not null unique,
    type        text not null,
    rules       jsonb not null,
    priority    int not null,
    stackable   boolean not null,
    starts_at   timestamptz,
    ends_at     timestamptz,
    active      boolean not null,
    change_txid xid8 not null default pg_current_xact_id()
);

-- Header row per store and SKU: every writer locks it, so the check against zero and the counter update are one
-- atomic step. on_hand is the PN-counter value, kept in step with stock_counter in the same transaction.
create table stock_item (
    store_code  text not null references store,
    sku         text not null references product,
    on_hand     bigint not null,
    change_txid xid8 not null default pg_current_xact_id(),
    primary key (store_code, sku)
);

create table stock_counter (
    store_code  text not null,
    sku         text not null,
    node        text not null,
    inc         bigint not null default 0 check (inc >= 0),
    dec         bigint not null default 0 check (dec >= 0),
    primary key (store_code, sku, node),
    foreign key (store_code, sku) references stock_item
);

create table stock_movement (
    id          bigserial primary key,
    store_code  text not null,
    sku         text not null,
    node        text not null,
    delta       bigint not null,
    on_hand     bigint not null,
    cause       text not null,
    ref         text not null,
    at          timestamptz not null
);
create index stock_movement_item on stock_movement (store_code, sku, id);

create table invoice_series (
    series       text primary key,
    store_code   text not null references store,
    terminal_id  uuid references terminal,
    fy           int not null,
    next_no      int not null
);

create table invoice_block (
    series       text not null references invoice_series,
    first_no     int not null,
    last_no      int not null,
    terminal_id  uuid not null references terminal,
    allocated_at timestamptz not null,
    primary key (series, first_no)
);

create table shift (
    id              uuid primary key,
    store_code      text not null references store,
    terminal_id     uuid references terminal,
    cashier         text not null,
    status          text not null,
    opening_float   numeric(12, 2) not null,
    opened_at       timestamptz not null,
    closed_at       timestamptz,
    declared_sales  int,
    counted_cash    numeric(12, 2),
    expected_cash   numeric(12, 2),
    variance        numeric(12, 2)
);

-- id is generated by the device, so a retried upload of the same sale is recognised.
create table sale (
    id               uuid primary key,
    store_code       text not null references store,
    terminal_id      uuid references terminal,
    shift_id         uuid references shift,
    local_seq        bigint,
    channel          text not null check (channel in ('ONLINE', 'OFFLINE')),
    invoice_no       text not null unique,
    status           text not null,
    cashier          text not null,
    place_of_supply  char(2),
    customer_gstin   text,
    gross            numeric(14, 2) not null,
    discount         numeric(14, 2) not null,
    taxable          numeric(14, 2) not null,
    cgst             numeric(14, 2) not null,
    sgst             numeric(14, 2) not null,
    igst             numeric(14, 2) not null,
    total            numeric(14, 2) not null,
    change_due       numeric(14, 2) not null,
    refunded         numeric(14, 2) not null default 0,
    request_hash     text not null,
    sold_at          timestamptz not null,
    synced_at        timestamptz not null
);
create index sale_store_day on sale (store_code, sold_at);
create index sale_shift on sale (shift_id);

create table sale_line (
    sale_id          uuid not null references sale,
    line_no          int not null,
    sku              text not null,
    qty              int not null check (qty > 0),
    unit_price       numeric(12, 2) not null,
    tax_rate         numeric(5, 2) not null,
    promo_discount   numeric(14, 2) not null,
    manual_discount  numeric(14, 2) not null,
    taxable          numeric(14, 2) not null,
    cgst             numeric(14, 2) not null,
    sgst             numeric(14, 2) not null,
    igst             numeric(14, 2) not null,
    total            numeric(14, 2) not null,
    returned_qty     int not null default 0,
    refunded         numeric(14, 2) not null default 0,
    refunded_taxable numeric(14, 2) not null default 0,
    refunded_cgst    numeric(14, 2) not null default 0,
    refunded_sgst    numeric(14, 2) not null default 0,
    refunded_igst    numeric(14, 2) not null default 0,
    primary key (sale_id, line_no),
    check (returned_qty between 0 and qty)
);

create table payment (
    sale_id    uuid not null references sale,
    idx        int not null,
    method     text not null,
    amount     numeric(14, 2) not null check (amount > 0),
    reference  text,
    primary key (sale_id, idx)
);

create table sale_promotion (
    sale_id         uuid not null references sale,
    promotion_code  text not null,
    times           int not null,
    saving          numeric(14, 2) not null,
    primary key (sale_id, promotion_code)
);

create table credit_note (
    no          text primary key,
    store_code  text not null references store,
    sale_id     uuid not null references sale,
    amount      numeric(14, 2) not null check (amount > 0),
    used        numeric(14, 2) not null default 0,
    created_at  timestamptz not null,
    check (used between 0 and amount)
);

create table sale_return (
    id              uuid primary key,
    sale_id         uuid not null references sale,
    refund_method   text not null,
    amount          numeric(14, 2) not null,
    credit_note_no  text references credit_note,
    restock         boolean not null,
    shift_id        uuid references shift,
    request_hash    text not null,
    by_subject      text not null,
    at              timestamptz not null
);

create table sale_return_line (
    return_id  uuid not null references sale_return,
    line_no    int not null,
    qty        int not null,
    amount     numeric(14, 2) not null,
    primary key (return_id, line_no)
);

-- The terminal's op log as received. (terminal, epoch, seq) is the idempotency key.
create table op_log (
    terminal_id   uuid not null references terminal,
    epoch         int not null,
    seq           bigint not null,
    op_type       text not null,
    op_version    int not null,
    payload       jsonb not null,
    payload_hash  text not null,
    status        text not null check (status in ('APPLIED', 'REJECTED')),
    reason        text,
    received_at   timestamptz not null,
    primary key (terminal_id, epoch, seq)
);

create table purchase_order (
    id           uuid primary key,
    store_code   text not null references store,
    supplier_id  uuid not null references supplier,
    status       text not null,
    idem_key     text unique,
    created_by   text not null,
    created_at   timestamptz not null
);

create table po_line (
    po_id      uuid not null references purchase_order,
    sku        text not null references product,
    qty        int not null check (qty > 0),
    unit_cost  numeric(12, 2) not null check (unit_cost >= 0),
    received   int not null default 0,
    primary key (po_id, sku),
    check (received between 0 and qty)
);

create table grn (
    id           uuid primary key,
    po_id        uuid not null references purchase_order,
    ref          text not null,
    received_by  text not null,
    received_at  timestamptz not null,
    unique (po_id, ref)
);

create table grn_line (
    grn_id  uuid not null references grn,
    sku     text not null,
    qty     int not null check (qty >= 0),
    primary key (grn_id, sku)
);

create table transfer (
    id           uuid primary key,
    from_store   text not null references store,
    to_store     text not null references store,
    status       text not null check (status in ('IN_TRANSIT', 'RECEIVED')),
    created_by   text not null,
    created_at   timestamptz not null,
    received_at  timestamptz
);

create table transfer_line (
    transfer_id  uuid not null references transfer,
    sku          text not null references product,
    qty          int not null check (qty > 0),
    received     int,
    primary key (transfer_id, sku)
);

create table stock_count (
    id          uuid primary key,
    store_code  text not null references store,
    sku         text not null,
    book        bigint not null,
    counted     bigint not null,
    by_subject  text not null,
    at          timestamptz not null
);

create table alert (
    id          bigserial primary key,
    store_code  text not null,
    sku         text,
    type        text not null,
    detail      text not null,
    event_id    uuid not null,
    created_at  timestamptz not null,
    unique (event_id, type)
);
create index alert_store on alert (store_code, id desc);

-- Eventually consistent rollup fed from SaleCompleted / SaleReturned events.
create table sales_daily (
    store_code  text not null,
    day         date not null,
    sku         text not null,
    qty         bigint not null,
    net         numeric(16, 2) not null,
    tax         numeric(16, 2) not null,
    primary key (store_code, day, sku)
);

create table sales_daily_store (
    store_code  text not null,
    day         date not null,
    invoices    bigint not null,
    returns     bigint not null,
    total       numeric(16, 2) not null,
    primary key (store_code, day)
);

create table outbox (
    id            bigserial primary key,
    event_id      uuid not null unique,
    topic         text not null,
    msg_key       text not null,
    type          text not null,
    payload       jsonb not null,
    created_at    timestamptz not null,
    published_at  timestamptz
);
create index outbox_unpublished on outbox (id) where published_at is null;

create table processed_event (
    consumer  text not null,
    event_id  uuid not null,
    at        timestamptz not null,
    primary key (consumer, event_id)
);
